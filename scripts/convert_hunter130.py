"""Vendor the Hunter130 URDF/meshes and generate its training MJCF.

Run in the mjlab conda environment. Geometry and inertial transforms use URDF
fixed-axis RPY; primitive collision shapes are fitted in each mesh's local frame.
"""

import argparse
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation


ASSET_DIR = Path(__file__).resolve().parents[1] / "src/assets/robots/hunter130"


def numbers(values) -> str:
  return " ".join(f"{v:.10g}" for v in values)


def mesh_vertices(path: Path) -> np.ndarray:
  """Read the binary STL files provided by the SolidWorks exporter."""
  with path.open("rb") as stream:
    stream.read(80)
    count = int.from_bytes(stream.read(4), "little")
    dtype = np.dtype([("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attr", "<u2")])
    faces = np.fromfile(stream, dtype=dtype, count=count)
  if len(faces) != count or count == 0:
    raise ValueError(f"Invalid binary STL: {path}")
  return faces["vertices"].reshape(-1, 3).astype(np.float64)


def mujoco_mesh(path: Path) -> str:
  """Losslessly convert oversized STLs to indexed OBJ (MuJoCo STL cap: 200k)."""
  vertices = mesh_vertices(path)
  if len(vertices) // 3 <= 200000:
    return path.name
  unique, indices = np.unique(vertices, axis=0, return_inverse=True)
  output = path.with_suffix(".obj")
  with output.open("w") as stream:
    stream.write("# Lossless indexed conversion of " + path.name + "\n")
    np.savetxt(stream, unique, fmt="v %.10g %.10g %.10g")
    np.savetxt(stream, indices.reshape(-1, 3) + 1, fmt="f %d %d %d")
  return output.name


def origin(element: ET.Element) -> dict[str, str]:
  node = element.find("origin")
  if node is None:
    return {}
  rpy = np.fromstring(node.get("rpy", "0 0 0"), sep=" ")
  xyzw = Rotation.from_euler("xyz", rpy).as_quat()
  return {"pos": node.get("xyz", "0 0 0"), "quat": numbers(xyzw[[3, 0, 1, 2]])}


def convert(
  source_dir: Path, output_dir: Path = ASSET_DIR, *, robot_name: str = "hunter130",
  urdf_relative_path: str = "EC-H130-V2_URDF.urdf", root_height: float = 0.68,
  expected_joint_count: int = 25,
) -> Path:
  urdf_path = source_dir / urdf_relative_path
  urdf = ET.parse(urdf_path)
  source = urdf.getroot()
  source.set("name", robot_name)
  output_dir.mkdir(parents=True, exist_ok=True)
  (output_dir / "xmls").mkdir(exist_ok=True)
  for mesh in source.findall(".//mesh"):
    mesh_source = (urdf_path.parent / mesh.attrib["filename"]).resolve()
    relative = Path("meshes") / mesh_source.name
    target = output_dir / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if mesh_source != target.resolve():
      shutil.copy2(mesh_source, target)
    mesh.set("filename", relative.as_posix())
  urdf.write(output_dir / f"{robot_name}.urdf", encoding="utf-8", xml_declaration=True)

  model = ET.Element("mujoco", model=robot_name)
  model.append(ET.Comment(f"Generated by scripts/convert_{robot_name}.py; dynamics from {robot_name}.urdf."))
  ET.SubElement(model, "compiler", angle="radian", meshdir="../meshes", autolimits="true", inertiafromgeom="false")
  defaults = ET.SubElement(model, "default")
  visual = ET.SubElement(defaults, "default", {"class": "visual"})
  ET.SubElement(visual, "geom", type="mesh", density="0", contype="0", conaffinity="0", group="2", rgba="0.8 0.8 0.82 1")
  collision = ET.SubElement(defaults, "default", {"class": "collision"})
  ET.SubElement(collision, "geom", density="0", group="3", condim="1", friction="0.6 0.005 0.0001", rgba="0.3 0.6 0.8 0.3")
  asset = ET.SubElement(model, "asset")
  links = {link.attrib["name"]: link for link in source.findall("link")}
  joints = source.findall("joint")
  children: dict[str, list[ET.Element]] = {}
  parents: dict[str, str] = {}
  for joint in joints:
    parent = joint.find("parent").attrib["link"]
    child = joint.find("child").attrib["link"]
    children.setdefault(parent, []).append(joint)
    parents[child] = parent
  roots = links.keys() - parents.keys()
  if roots != {"pelvis"} or len(joints) != expected_joint_count:
    raise ValueError(f"Expected {robot_name} with {expected_joint_count} joints and pelvis root")
  world = ET.SubElement(model, "worldbody")

  def add_link(name: str, parent_body: ET.Element, joint: ET.Element | None = None):
    link = links[name]
    body = ET.SubElement(parent_body, "body", name=name, **(origin(joint) if joint is not None else {"pos": f"0 0 {root_height}"}))
    inertial = link.find("inertial")
    inertia = inertial.find("inertia").attrib
    tensor = np.array([[float(inertia["ixx"]), float(inertia["ixy"]), float(inertia["ixz"])],
                       [float(inertia["ixy"]), float(inertia["iyy"]), float(inertia["iyz"])],
                       [float(inertia["ixz"]), float(inertia["iyz"]), float(inertia["izz"])]])
    io = inertial.find("origin")
    rotation = Rotation.from_euler("xyz", np.fromstring(io.get("rpy", "0 0 0"), sep=" ")).as_matrix()
    tensor = rotation @ tensor @ rotation.T
    ET.SubElement(body, "inertial", pos=io.get("xyz", "0 0 0"), mass=inertial.find("mass").attrib["value"],
                  fullinertia=numbers([tensor[0, 0], tensor[1, 1], tensor[2, 2], tensor[0, 1], tensor[0, 2], tensor[1, 2]]))
    if joint is None:
      ET.SubElement(body, "freejoint", name="floating_base_joint")
      ET.SubElement(body, "site", name="imu_in_pelvis", pos="0 0 0", size="0.01", group="5")
    else:
      if joint.attrib["type"] != "revolute":
        raise ValueError(f"Unsupported joint: {joint.attrib}")
      limit = joint.find("limit").attrib
      ET.SubElement(body, "joint", name=joint.attrib["name"], type="hinge", axis=joint.find("axis").attrib["xyz"],
                    range=f"{limit['lower']} {limit['upper']}", actuatorfrcrange=f"-{limit['effort']} {limit['effort']}")
    visual_node = link.find("visual")
    filename = Path(visual_node.find("geometry/mesh").attrib["filename"]).name
    ET.SubElement(asset, "mesh", name=name, file=mujoco_mesh(output_dir / "meshes" / filename))
    ET.SubElement(body, "geom", {"name": f"{name}_visual", "class": "visual", "mesh": name, **origin(visual_node)})

    # Keep original foot meshes; fit primitive collisions to the other CAD parts.
    collision_node = link.find("collision")
    collision_file = collision_node.find("geometry/mesh").attrib["filename"]
    vertices = mesh_vertices(output_dir / collision_file)
    lower, upper = vertices.min(axis=0), vertices.max(axis=0)
    center, half = (lower + upper) / 2, (upper - lower) / 2
    frame = origin(collision_node)
    xyzw = np.asarray([float(v) for v in frame["quat"].split()])[[1, 2, 3, 0]]
    rotation = Rotation.from_quat(xyzw)
    offset = np.fromstring(frame["pos"], sep=" ")
    attrs = {"name": f"{name}_collision", "class": "collision"}
    if name.endswith("ankle_roll_link"):
      side = name.split("_")[0]
      if Path(collision_file).name != filename:
        raise ValueError(f"Foot visual/collision mesh mismatch: {name}")
      attrs.update(name=f"{side}_foot_collision", type="mesh", mesh=name, **frame, condim="3", priority="1")
      ET.SubElement(body, "site", name=f"{side}_foot", pos=numbers(rotation.apply([center[0], center[1], lower[2]]) + offset), size="0.01", group="5")
    elif name in ("pelvis", "torso_link"):
      attrs.update(type="box", pos=numbers(rotation.apply(center) + offset), quat=frame["quat"], size=numbers(half))
    else:
      axis = int(np.argmax(half))
      radius = float(min(np.delete(half, axis)))
      start, end = center.copy(), center.copy()
      length = max(float(half[axis]) - radius, 0.001)
      start[axis] -= length
      end[axis] += length
      attrs.update(type="capsule", size=numbers([radius]), fromto=numbers(np.r_[rotation.apply(start) + offset, rotation.apply(end) + offset]))
    ET.SubElement(body, "geom", attrs)
    for child_joint in children.get(name, []):
      add_link(child_joint.find("child").attrib["link"], body, child_joint)

  add_link("pelvis", world)
  # CAD joint housings overlap along the chain; exclude pairs within two joints.
  contact = ET.SubElement(model, "contact")
  for child, parent in parents.items():
    ET.SubElement(contact, "exclude", body1=parent, body2=child)
    if parent in parents:
      ET.SubElement(contact, "exclude", body1=parents[parent], body2=child)
  sensors = ET.SubElement(model, "sensor")
  for tag, name in (("gyro", "imu_ang_vel"), ("velocimeter", "imu_lin_vel"), ("accelerometer", "imu_lin_acc")):
    ET.SubElement(sensors, tag, name=name, site="imu_in_pelvis")
  ET.SubElement(sensors, "subtreeangmom", name="root_angmom", body="pelvis")
  ET.indent(model, space="  ")
  path = output_dir / f"xmls/{robot_name}.xml"
  ET.ElementTree(model).write(path, encoding="utf-8", xml_declaration=True)
  return path


if __name__ == "__main__":
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--source-dir", type=Path, default=Path("/home/milkyway/opensource/EC-R130-V2_description"))
  parser.add_argument("--output-dir", type=Path, default=ASSET_DIR)
  args = parser.parse_args()
  print(convert(args.source_dir, args.output_dir))
